	/** 前端用：所有合法的 3 碼區號（已排序） */
	public static List<String> areaCodes() {
		return List.copyOf(AREA_CODES);
	}

	/** 3 碼，或 3+3 共 6 碼，且前 3 碼是真的存在的區號 */
	public static boolean isValid(String code) {
		if (code == null) {
			return false;
		}
		String c = code.trim();
		if (!c.matches("\\d{3}(\\d{3})?")) {
			return false;
		}
		return AREA_CODES.contains(c.substring(0, 3));
	}

	/** 存進資料庫用；不合法回傳 null */
	public static Integer toInteger(String code) {
		return isValid(code) ? Integer.valueOf(code.trim()) : null;
	}
